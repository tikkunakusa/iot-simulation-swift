    /// Kecepatan simulasi:
    /// 1.0  = Waktu Nyata 4 Jam (~50 km/jam rata-rata truk kargo mangga)
    /// 10.0 = 10x lebih cepat (~24 menit perjalanan rute lengkap)
    /// 30.0 = 30x lebih cepat (~8 menit perjalanan rute lengkap untuk testing)
    public var speedMultiplier: Double = 1.0

    /// Kecepatan rata-rata kendaraan truk (km/jam): 200.4 km / 4 jam = ~50 km/jam
    public var baseSpeedKmh: Double = 50.0

    /// Indeks progres kontinu (0.0 hingga 3599.0)
    private var currentIndex: Double = 0.0
    public private(set) var isArrived: Bool = false
    private var randomSeed: UInt32 = 54321

    /// Total jarak rute nyata (meter)
    public let totalRouteDistanceMeters: Double = 200382.0

    private init() {}

    /// Pseudo-random jitter (+/- 2-3 meter) untuk mensimulasikan noise GPS organik
    private func pseudoRandomJitter() -> Double {
        randomSeed = (randomSeed &* 1103515245 &+ 12345) & 0x7fffffff
        let normalized = Double(randomSeed % 1000) / 1000.0 // 0.0 ... 1.0
        return (normalized - 0.5) * 0.00003 // +/- ~2-3m
    }

    /// Memperbarui posisi kendaraan untuk interval waktu tertentu (default 1.0 detik)
    public func update(deltaTimeSeconds: Double = 1.0) -> GPSData {
        guard !waypoints.isEmpty else {
            return GPSData(latitude: -6.289060, longitude: 106.871800)
        }

        if isArrived || currentIndex >= Double(waypoints.count - 1) {
            let dest = waypoints.last!
            return GPSData(latitude: dest.lat + pseudoRandomJitter(), longitude: dest.lon + pseudoRandomJitter())
        }

        // Jarak rata-rata antar waypoint ~55.68 meter
        let distancePerWaypoint = totalRouteDistanceMeters / Double(waypoints.count - 1)
        let speedMps = (baseSpeedKmh * 1000.0 / 3600.0) * speedMultiplier
        let distanceAdvance = speedMps * deltaTimeSeconds

        currentIndex += (distanceAdvance / distancePerWaypoint)

        if currentIndex >= Double(waypoints.count - 1) {
            currentIndex = Double(waypoints.count - 1)
            isArrived = true
            print("\n[SIM-GPS] 🏁 TRUK TELAH TIBA DI TUJUAN AKHIR: PASAR INDUK KRAMAT JATI, JAKARTA TIMUR!\n")
        }

        let lowerIndex = Int(currentIndex)
        let upperIndex = min(lowerIndex + 1, waypoints.count - 1)
        let fractionalProgress = currentIndex - Double(lowerIndex)

        let p1 = waypoints[lowerIndex]
        let p2 = waypoints[upperIndex]

        // Interpolasi Linier (Lerp) presisi tinggi antar 2 waypoint terdekat
        let lat = p1.lat + fractionalProgress * (p2.lat - p1.lat) + pseudoRandomJitter()
        let lon = p1.lon + fractionalProgress * (p2.lon - p1.lon) + pseudoRandomJitter()

        return GPSData(latitude: lat, longitude: lon)
    }

    /// Persentase kemajuan rute (0.0% ... 100.0%)
    public var progressPercentage: Double {
        return (currentIndex / Double(max(1, waypoints.count - 1))) * 100.0
    }

    /// Indeks titik waypoint saat ini (1 s.d. 3600)
    public var currentWaypointNumber: Int {
        return min(Int(currentIndex) + 1, waypoints.count)
    }

    /// Deskripsi lokasi berdasarkan milestone rute saat ini
    public var currentLegDescription: String {
        if isArrived {
